class IntentConflictError(RuntimeError):
    """The same client-order ID was reused for a different intent."""


class IntentInFlightError(RuntimeError):
    """A prior submission is unresolved; resubmission would risk a duplicate fill."""


class OrderIntentStore:
    TERMINAL = {"ACCEPTED", "PARTIALLY_FILLED", "FILLED", "CANCELLED", "REJECTED", "UNKNOWN"}
    PROGRESSIONS = {
        "RESERVED": {"RESERVED", "SUBMITTING", "ACCEPTED", "PARTIALLY_FILLED", "FILLED",
                     "CANCELLED", "REJECTED", "UNKNOWN"},
        "SUBMITTING": {"SUBMITTING", "ACCEPTED", "PARTIALLY_FILLED", "FILLED", "CANCELLED",
                       "REJECTED", "UNKNOWN"},
        "UNKNOWN": {"UNKNOWN", "ACCEPTED", "PARTIALLY_FILLED", "FILLED", "CANCELLED", "REJECTED"},
        "ACCEPTED": {"ACCEPTED", "PARTIALLY_FILLED", "FILLED", "CANCELLED", "REJECTED"},
        "PARTIALLY_FILLED": {"PARTIALLY_FILLED", "FILLED", "CANCELLED"},
        "FILLED": {"FILLED"},
        "CANCELLED": {"CANCELLED"},
        "REJECTED": {"REJECTED"},
    }

    def __init__(self, path: str | None = None):
        # Prefer the agent's authoritative database when configured. Explicit
        # paths remain useful for isolated SQLite unit tests and local dev.
        configured_dsn = (os.getenv("STRATEX_DATABASE_URL") or "").strip()
        if path is not None:
            self.path = path
        elif configured_dsn:
            if not configured_dsn.lower().startswith(POSTGRES_PREFIXES + ORACLE_PREFIXES):
                raise RuntimeError(
                    "STRATEX_DATABASE_URL must use PostgreSQL or Oracle; refusing an implicit "
                    "local-ledger fallback."
                )
            self.path = configured_dsn
        else:
            raise RuntimeError(
                "Stratex OMS/reconciliation requires STRATEX_DATABASE_URL pointing to an "
                "Oracle Autonomous Database; SQLite and PostgreSQL are not supported "
                "production backends. Pass an explicit path only in isolated tests."
            )
        self._dialect = detect_dialect(self.path)
        self._use_postgres = self._dialect == "postgresql"
        self._use_oracle = self._dialect == "oracle"
        self._dsn = self.path
        if self._use_postgres:
            if self._dsn.startswith("postgresql+psycopg://"):
                self._dsn = "postgresql://" + self._dsn[len("postgresql+psycopg://"):]
            elif self._dsn.startswith("postgres://"):
                self._dsn = "postgresql://" + self._dsn[len("postgres://"):]
        elif self._use_oracle:
            self._dsn = normalize_oracle_dsn(self._dsn)
        if not (self._use_postgres or self._use_oracle) and self.path != ":memory:":
            Path(self.path).parent.mkdir(parents=True, exist_ok=True)
        self._oracle = (
            OracleDatabase(self._dsn, component="order ledger") if self._use_oracle else None
        )
        self._initialize()

    def _connect(self):
        if self._use_postgres:
            try:
                import psycopg
                from psycopg.rows import dict_row
            except ImportError as exc:  # pragma: no cover - packaging guard
                raise RuntimeError("PostgreSQL order storage requires psycopg 3.") from exc
            return psycopg.connect(self._dsn, row_factory=dict_row, connect_timeout=5)
        if self._use_oracle:  # pragma: no cover - defensive: Oracle uses SQLAlchemy
            raise RuntimeError("Oracle connections are managed through SQLAlchemy; use _managed_connection().")
        conn = sqlite3.connect(self.path, timeout=10.0)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA busy_timeout=10000")
        conn.execute("PRAGMA foreign_keys=ON")
        return conn

    def _sql(self, statement: str) -> str:
        """Translate query placeholders for psycopg while preserving SQLite SQL."""
        return statement.replace("?", "%s") if self._use_postgres else statement

    @contextmanager
    def _managed_connection(self):
        """Close SQLite connections reliably; Connection.__exit__ only commits/rolls back.

        Oracle connections come from the SQLAlchemy pool and use an explicit
        transaction so a failed statement can be rolled back without closing
        the pooled connection.
        """
        if self._use_oracle:
            assert self._oracle is not None
            with self._oracle.connection() as oracle_conn:
                yield oracle_conn
            return
        conn = self._connect()
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()

    def _initialize(self) -> None:
        if self._use_oracle:
            self._initialize_oracle()
            return
        with self._managed_connection() as conn:
            if self._use_postgres:
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS order_intents (
                        client_order_id TEXT PRIMARY KEY, payload_hash TEXT NOT NULL,
                        payload_json TEXT NOT NULL, status TEXT NOT NULL, result_json TEXT,
                        error_text TEXT, created_at DOUBLE PRECISION NOT NULL,
                        updated_at DOUBLE PRECISION NOT NULL
                    )
                """)
            else:
                conn.execute("PRAGMA journal_mode=WAL")
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS order_intents (
                        client_order_id TEXT PRIMARY KEY, payload_hash TEXT NOT NULL,
                        payload_json TEXT NOT NULL, status TEXT NOT NULL, result_json TEXT,
                        error_text TEXT, created_at REAL NOT NULL, updated_at REAL NOT NULL
                    )
                """)
            conn.execute("CREATE INDEX IF NOT EXISTS idx_order_intents_status ON order_intents(status)")
            if self._use_postgres:
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS order_audit_events (
                        event_id BIGSERIAL PRIMARY KEY, client_order_id TEXT NOT NULL,
                        event_type TEXT NOT NULL, previous_status TEXT, new_status TEXT,
                        details_json TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL,
                        FOREIGN KEY(client_order_id) REFERENCES order_intents(client_order_id)
                    )
                """)
            else:
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS order_audit_events (
                        event_id INTEGER PRIMARY KEY AUTOINCREMENT, client_order_id TEXT NOT NULL,
                        event_type TEXT NOT NULL, previous_status TEXT, new_status TEXT,
                        details_json TEXT NOT NULL, created_at REAL NOT NULL,
                        FOREIGN KEY(client_order_id) REFERENCES order_intents(client_order_id)
                    )
                """)
            conn.execute("CREATE INDEX IF NOT EXISTS idx_order_audit_client_time ON order_audit_events(client_order_id, created_at)")
            if self._use_postgres:
                conn.execute("""
                    CREATE OR REPLACE FUNCTION stratex_order_audit_immutable()
                    RETURNS TRIGGER AS $$
                    BEGIN
                        RAISE EXCEPTION 'audit events are append-only';
                    END;
                    $$ LANGUAGE plpgsql
                """)
                conn.execute("DROP TRIGGER IF EXISTS order_audit_no_update ON order_audit_events")
                conn.execute("DROP TRIGGER IF EXISTS order_audit_no_delete ON order_audit_events")
                conn.execute("""
                    CREATE TRIGGER order_audit_no_update BEFORE UPDATE ON order_audit_events
                    FOR EACH ROW EXECUTE FUNCTION stratex_order_audit_immutable()
                """)
                conn.execute("""
                    CREATE TRIGGER order_audit_no_delete BEFORE DELETE ON order_audit_events
                    FOR EACH ROW EXECUTE FUNCTION stratex_order_audit_immutable()
                """)
            else:
                conn.execute("""
                    CREATE TRIGGER IF NOT EXISTS order_audit_no_update BEFORE UPDATE ON order_audit_events
                    BEGIN SELECT RAISE(ABORT, 'audit events are append-only'); END
                """)
                conn.execute("""
                    CREATE TRIGGER IF NOT EXISTS order_audit_no_delete BEFORE DELETE ON order_audit_events
                    BEGIN SELECT RAISE(ABORT, 'audit events are append-only'); END
                """)

    def _initialize_oracle(self) -> None:
        """Idempotently create the Oracle ledger objects in the current schema.

        Oracle DDL auto-commits, so bootstrap runs in its own connection before
        any business transaction. Existing objects are left untouched; missing
        objects are created and logged. Any failure is logged and re-raised.
        """
        assert self._oracle is not None
        with self._oracle.connection() as conn:
            schema = self._oracle.current_schema(conn)
            logger.info(
                "Stratex order ledger Oracle bootstrap: schema=%s target=%s",
                schema,
                redact_dsn(self._dsn),
            )
            self._oracle.ensure_table(conn, "ORDER_INTENTS", _ORACLE_ORDER_INTENTS_DDL)
            self._oracle.ensure_index(
                conn, "IDX_ORDER_INTENTS_STATUS", _ORACLE_ORDER_INTENTS_STATUS_DDL
            )
            self._oracle.ensure_table(conn, "ORDER_AUDIT_EVENTS", _ORACLE_ORDER_AUDIT_EVENTS_DDL)
            self._oracle.ensure_index(
                conn, "IDX_ORDER_AUDIT_CLIENT_TIME", _ORACLE_ORDER_AUDIT_CLIENT_TIME_DDL
            )
            self._oracle.ensure_trigger(
                conn, "ORDER_AUDIT_NO_UPDATE", _ORACLE_ORDER_AUDIT_NO_UPDATE_DDL
            )
            self._oracle.ensure_trigger(
                conn, "ORDER_AUDIT_NO_DELETE", _ORACLE_ORDER_AUDIT_NO_DELETE_DDL
            )

    def _append_audit_event(self, conn, *, client_order_id: str, event_type: str,
                            previous_status: str | None, new_status: str | None,
                            details: dict[str, Any], timestamp: float) -> None:
        details_json = json.dumps(details, sort_keys=True, separators=(",", ":"), allow_nan=False)
        if self._use_oracle:
            assert self._oracle is not None
            self._oracle.execute(
                conn,
                "INSERT INTO order_audit_events "
                "(client_order_id,event_type,previous_status,new_status,details_json,created_at) "
                "VALUES (:client_order_id,:event_type,:previous_status,:new_status,"
                ":details_json,:created_at)",
                {
                    "client_order_id": client_order_id,
                    "event_type": event_type,
                    "previous_status": previous_status,
                    "new_status": new_status,
                    "details_json": details_json,
                    "created_at": timestamp,
                },
            )
            return
        conn.execute(self._sql(
            "INSERT INTO order_audit_events "
            "(client_order_id,event_type,previous_status,new_status,details_json,created_at) "
            "VALUES (?,?,?,?,?,?)"
        ), (client_order_id, event_type, previous_status, new_status, details_json, timestamp))

    @staticmethod
    def _result_summary(result: dict[str, Any] | None) -> dict[str, Any] | None:
        if not isinstance(result, dict):
            return None
        allowed = (
            "status", "order_id", "deal", "avg_price", "price", "quantity",
            "volume_filled", "venue", "environment", "protection_verified",
            "stop_algo_id", "take_profit_algo_id", "reason",
        )
        summary = {key: result[key] for key in allowed if key in result}
        return summary

    def reserve(self, client_order_id: str, payload_hash: str, payload: dict[str, Any]) -> dict[str, Any]:
        """Atomically reserve an ID. Returns whether it is new or an existing intent."""
        now = time.time()
        payload_json = json.dumps(payload, sort_keys=True, separators=(",", ":"), allow_nan=False)
        safe_payload = {key: payload.get(key) for key in
                        ("venue", "symbol", "side", "environment", "quantity", "strategy") if key in payload}
        if self._use_oracle:
            return self._reserve_oracle(
                client_order_id=client_order_id,
                payload_hash=payload_hash,
                payload_json=payload_json,
                safe_payload=safe_payload,
                now=now,
            )
        with self._managed_connection() as conn:
            if self._use_postgres:
                inserted = conn.execute(
                    "INSERT INTO order_intents "
                    "(client_order_id,payload_hash,payload_json,status,created_at,updated_at) "
                    "VALUES (%s,%s,%s,%s,%s,%s) ON CONFLICT (client_order_id) DO NOTHING RETURNING client_order_id",
                    (client_order_id, payload_hash, payload_json, "RESERVED", now, now),
                ).fetchone()
                if inserted is not None:
                    self._append_audit_event(conn, client_order_id=client_order_id, event_type="INTENT_RESERVED",
                                              previous_status=None, new_status="RESERVED",
                                              details={"payload_hash": payload_hash, **safe_payload}, timestamp=now)
                    return {"kind": "new", "status": "RESERVED"}
                row = conn.execute(
                    "SELECT * FROM order_intents WHERE client_order_id = %s FOR UPDATE", (client_order_id,)
                ).fetchone()
            else:
                conn.execute("BEGIN IMMEDIATE")
                row = conn.execute(
                    "SELECT * FROM order_intents WHERE client_order_id = ?", (client_order_id,)
                ).fetchone()
                if row is None:
                    conn.execute(
                        "INSERT INTO order_intents "
                        "(client_order_id,payload_hash,payload_json,status,created_at,updated_at) "
                        "VALUES (?,?,?,?,?,?)",
                        (client_order_id, payload_hash, payload_json, "RESERVED", now, now),
                    )
                    self._append_audit_event(conn, client_order_id=client_order_id, event_type="INTENT_RESERVED",
                                              previous_status=None, new_status="RESERVED",
                                              details={"payload_hash": payload_hash, **safe_payload}, timestamp=now)
                    return {"kind": "new", "status": "RESERVED"}
            if row is None:
                raise RuntimeError("Order intent conflict resolved but existing row was not found")
            return self._existing_intent_result(
                conn, row_to_dict(row), client_order_id=client_order_id,
                payload_hash=payload_hash, now=now,
            )

    def _reserve_oracle(self, *, client_order_id: str, payload_hash: str, payload_json: str,
                        safe_payload: dict[str, Any], now: float) -> dict[str, Any]:
        """Insert-or-lock a reservation using Oracle unique-key semantics.

        ``INSERT`` is attempted first so the primary key, not a pre-read, decides
        the winner between concurrent workers. ORA-00001 means another
        transaction owns the ID; Oracle does not poison the transaction, so the
        row is then locked with ``FOR UPDATE`` and inspected. A visible row must
        exist after a committed duplicate; if a competing transaction rolled
        back instead, one retry inserts normally. This is the Oracle equivalent
        of ``ON CONFLICT DO NOTHING RETURNING``.
        """
        assert self._oracle is not None
        insert_sql = (
            "INSERT INTO order_intents "
            "(client_order_id,payload_hash,payload_json,status,created_at,updated_at) "
            "VALUES (:client_order_id,:payload_hash,:payload_json,"
            ":status,:created_at,:updated_at)"
        )
        insert_params = {
            "client_order_id": client_order_id,
            "payload_hash": payload_hash,
            "payload_json": payload_json,
            "status": "RESERVED",
            "created_at": now,
            "updated_at": now,
        }
        with self._oracle.connection() as conn:
            row: dict[str, Any] | None = None
            for _attempt in range(2):
                try:
                    self._oracle.execute(conn, insert_sql, insert_params)
                except Exception as exc:
                    if oracle_error_code(exc) != "ORA-00001":
                        raise
                else:
                    self._append_audit_event(
                        conn, client_order_id=client_order_id, event_type="INTENT_RESERVED",
                        previous_status=None, new_status="RESERVED",
                        details={"payload_hash": payload_hash, **safe_payload}, timestamp=now,
                    )
                    return {"kind": "new", "status": "RESERVED"}
                row = self._oracle.fetchone(
                    conn,
                    "SELECT * FROM order_intents WHERE client_order_id = :client_order_id FOR UPDATE",
                    {"client_order_id": client_order_id},
                )
                if row is not None:
                    break
            if row is None:
                raise RuntimeError("Order intent conflict resolved but existing row was not found")
            return self._existing_intent_result(
                conn, row, client_order_id=client_order_id, payload_hash=payload_hash, now=now,
            )

    def _existing_intent_result(self, conn, row: dict[str, Any], *, client_order_id: str,
                                payload_hash: str, now: float) -> dict[str, Any]:
        if row["payload_hash"] != payload_hash:
            raise IntentConflictError("client_order_id already belongs to a different trade intent")
        if row["status"] in {"RESERVED", "SUBMITTING", "UNKNOWN"}:
            raise IntentInFlightError(
                f"Intent {client_order_id} has unresolved status {row['status']}; reconcile before retrying"
            )
        self._append_audit_event(conn, client_order_id=client_order_id, event_type="DUPLICATE_REQUEST",
                                  previous_status=row["status"], new_status=row["status"],
                                  details={"payload_hash": payload_hash}, timestamp=now)
        result_json = clob_text(row.get("result_json"))
        return {
            "kind": "duplicate",
            "status": row["status"],
            "result": json.loads(result_json) if result_json else None,
            "error": clob_text(row.get("error_text")),
        }

    @staticmethod
    def _oracle_intent_rows(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
        """Convert the CLOB ``error_text`` column to ``str`` for list results."""
        for row in rows:
            row["error_text"] = clob_text(row.get("error_text"))
        return rows

    def transition(self, client_order_id: str, status: str, *,
                   result: dict[str, Any] | None = None, error: str | None = None) -> None:
        allowed = {"RESERVED", "SUBMITTING", *self.TERMINAL}
        if status not in allowed:
            raise ValueError(f"Unsupported order state: {status}")
        now = time.time()
        result_json = json.dumps(result, sort_keys=True, separators=(",", ":"), allow_nan=False) if result is not None else None
        if self._use_oracle:
            self._transition_oracle(
                client_order_id, status, result=result, result_json=result_json,
                error=error, now=now,
            )
            return
        with self._managed_connection() as conn:
            row = conn.execute(self._sql("SELECT status FROM order_intents WHERE client_order_id=?"),
                                (client_order_id,)).fetchone()
            if row is None:
                raise KeyError(f"Unknown order intent: {client_order_id}")
            previous_status = str(row["status"]).upper()
            if status not in self.PROGRESSIONS.get(previous_status, set()):
                raise ValueError(f"Invalid order lifecycle transition: {previous_status} -> {status}")
            cur = conn.execute(self._sql(
                "UPDATE order_intents SET status=?, result_json=COALESCE(?, result_json), "
                "error_text=?, updated_at=? WHERE client_order_id=?"
            ), (status, result_json, error, now, client_order_id))
            if cur.rowcount != 1:
                raise KeyError(f"Unknown order intent: {client_order_id}")
            self._append_audit_event(
                conn, client_order_id=client_order_id, event_type="ORDER_STATE_TRANSITION",
                previous_status=previous_status, new_status=status,
                details={
                    "result": self._result_summary(result),
                    "error": str(error)[:300] if error else None,
                },
                timestamp=now,
            )

    def _transition_oracle(self, client_order_id: str, status: str, *,
                           result: dict[str, Any] | None, result_json: str | None,
                           error: str | None, now: float) -> None:
        """Oracle transition with a row lock and explicit COALESCE semantics.

        ``COALESCE`` on CLOB binds is unreliable across Oracle versions, so the
        existing result is read under ``FOR UPDATE`` and written back unchanged
        when no new result was supplied.
        """
        assert self._oracle is not None
        with self._oracle.connection() as conn:
            row = self._oracle.fetchone(
                conn,
                "SELECT status, result_json FROM order_intents "
                "WHERE client_order_id = :client_order_id FOR UPDATE",
                {"client_order_id": client_order_id},
            )
            if row is None:
                raise KeyError(f"Unknown order intent: {client_order_id}")
            previous_status = str(row["status"]).upper()
            if status not in self.PROGRESSIONS.get(previous_status, set()):
                raise ValueError(f"Invalid order lifecycle transition: {previous_status} -> {status}")
            effective_result_json = (
                result_json if result_json is not None else clob_text(row.get("result_json"))
            )
            cur = self._oracle.execute(
                conn,
                "UPDATE order_intents SET status=:status, "
                "result_json=:result_json, "
                "error_text=:error_text, updated_at=:updated_at "
                "WHERE client_order_id=:client_order_id",
                {
                    "status": status,
                    "result_json": effective_result_json,
                    "error_text": error,
                    "updated_at": now,
                    "client_order_id": client_order_id,
                },
            )
            if cur.rowcount != 1:
                raise KeyError(f"Unknown order intent: {client_order_id}")
            self._append_audit_event(
                conn, client_order_id=client_order_id, event_type="ORDER_STATE_TRANSITION",
                previous_status=previous_status, new_status=status,
                details={
                    "result": self._result_summary(result),
                    "error": str(error)[:300] if error else None,
                },
                timestamp=now,
            )

    def get(self, client_order_id: str) -> dict[str, Any] | None:
        with self._managed_connection() as conn:
            if self._use_oracle:
                assert self._oracle is not None
                row = self._oracle.fetchone(
                    conn,
                    "SELECT * FROM order_intents WHERE client_order_id = :client_order_id",
                    {"client_order_id": client_order_id},
                )
            else:
                row = conn.execute(self._sql("SELECT * FROM order_intents WHERE client_order_id=?"),
                                    (client_order_id,)).fetchone()
            if row is None:
                return None
            # Parse CLOB-backed JSON before the connection returns to the pool.
            item = row_to_dict(row)
            item["payload"] = json.loads(clob_text(item.pop("payload_json")))
            result_json = clob_text(item.pop("result_json"))
            item["result"] = json.loads(result_json) if result_json else None
            item["error_text"] = clob_text(item.get("error_text"))
            item.pop("payload_hash", None)
        return item

    def list_reconcilable(self, limit: int = 100) -> list[dict[str, Any]]:
        """List non-final or exchange-pending intents for periodic venue reconciliation."""
        limit = min(1000, max(1, int(limit)))
        with self._managed_connection() as conn:
            if self._use_oracle:
                assert self._oracle is not None
                return self._oracle_intent_rows(
                    self._oracle.fetchall(conn, _ORACLE_RECONCILABLE_SQL, {"row_limit": limit})
                )
            rows = conn.execute(self._sql(
                "SELECT client_order_id,status,created_at,updated_at,error_text "
                "FROM order_intents "
                "WHERE status IN ('RESERVED','SUBMITTING','UNKNOWN','ACCEPTED','PARTIALLY_FILLED') "
                "ORDER BY created_at ASC LIMIT ?"
            ), (limit,)).fetchall()
        return [row_to_dict(row) for row in rows]

    def record_correction(
        self,
        client_order_id: str,
        *,
        actor: str,
        reason: str,
        correction: dict[str, Any],
    ) -> None:
        """Append an explicit human/system correction note without rewriting history."""
        actor_value = str(actor).strip()
        reason_value = str(reason).strip()
        if not actor_value or not reason_value:
            raise ValueError("correction actor and reason are required")
        if not isinstance(correction, dict) or not correction:
            raise ValueError("correction must be a non-empty dictionary")
        allowed_fields = {"field", "old_value", "new_value", "reference"}
        if set(correction) - allowed_fields:
            raise ValueError("correction may contain only field, old_value, new_value and reference")
        now = time.time()
        with self._managed_connection() as conn:
            if self._use_oracle:
                assert self._oracle is not None
                row = self._oracle.fetchone(
                    conn,
                    "SELECT status FROM order_intents WHERE client_order_id = :client_order_id",
                    {"client_order_id": client_order_id},
                )
            else:
                row = conn.execute(self._sql("SELECT status FROM order_intents WHERE client_order_id=?"),
                                    (client_order_id,)).fetchone()
            if row is None:
                raise KeyError(f"Unknown order intent: {client_order_id}")
            current_status = str(row_to_dict(row)["status"])
            self._append_audit_event(
                conn,
                client_order_id=client_order_id,
                event_type="MANUAL_CORRECTION",
                previous_status=current_status,
                new_status=current_status,
                details={
                    "actor": actor_value[:100],
                    "reason": reason_value[:500],
                    "correction": correction,
                },
                timestamp=now,
            )

    def list_audit_events(
        self,
        *,
        client_order_id: str | None = None,
        limit: int = 1000,
    ) -> list[dict[str, Any]]:
        """Read append-only audit events in chronological order."""
        bounded_limit = min(10000, max(1, int(limit)))
        with self._managed_connection() as conn:
            if self._use_oracle:
                assert self._oracle is not None
                if client_order_id:
                    rows = self._oracle.fetchall(
                        conn,
                        "SELECT * FROM order_audit_events WHERE client_order_id = :client_order_id "
                        "ORDER BY event_id ASC FETCH FIRST :row_limit ROWS ONLY",
                        {"client_order_id": client_order_id, "row_limit": bounded_limit},
                    )
                else:
                    rows = self._oracle.fetchall(
                        conn,
                        "SELECT * FROM order_audit_events ORDER BY event_id ASC "
                        "FETCH FIRST :row_limit ROWS ONLY",
                        {"row_limit": bounded_limit},
                    )
            elif client_order_id:
                rows = conn.execute(self._sql(
                    "SELECT * FROM order_audit_events WHERE client_order_id=? ORDER BY event_id ASC LIMIT ?"
                ), (client_order_id, bounded_limit)).fetchall()
            else:
                rows = conn.execute(self._sql(
                    "SELECT * FROM order_audit_events ORDER BY event_id ASC LIMIT ?"
                ), (bounded_limit,)).fetchall()
            # Parse CLOB-backed JSON before the connection returns to the pool.
            result = []
            for row in rows:
                item = row_to_dict(row)
                item["details"] = json.loads(clob_text(item.pop("details_json")))
                result.append(item)
        return result

